-- ---------------------------------------------------------------------------
-- Tables
-- ---------------------------------------------------------------------------

create table if not exists public.items (
  id integer generated by default as identity primary key,
  sku text not null unique,
  name_en text not null,
  name_km text not null,
  category text not null default 'General',
  cost_price numeric(12, 2) not null check (cost_price >= 0),
  sell_price numeric(12, 2) not null check (sell_price >= 0),
  reorder_level integer not null default 0 check (reorder_level >= 0),
  created_at timestamptz not null default now()
);

create table if not exists public.purchases (
  id integer generated by default as identity primary key,
  po_no text not null unique,
  purchase_date date not null default current_date,
  supplier text not null,
  item_id integer not null references public.items (id) on delete restrict,
  qty integer not null check (qty > 0),
  unit_cost numeric(12, 2) not null check (unit_cost >= 0)
);

create table if not exists public.sales (
  id integer generated by default as identity primary key,
  inv_no text not null unique,
  sale_date date not null default current_date,
  customer text not null,
  item_id integer not null references public.items (id) on delete restrict,
  qty integer not null check (qty > 0),
  unit_price numeric(12, 2) not null check (unit_price >= 0)
);

create index if not exists purchases_item_id_idx on public.purchases (item_id);
create index if not exists purchases_date_idx on public.purchases (purchase_date);
create index if not exists sales_item_id_idx on public.sales (item_id);
create index if not exists sales_date_idx on public.sales (sale_date);

-- ---------------------------------------------------------------------------
-- Row Level Security
-- The browser never receives Supabase credentials; all access is server-side
-- with the service role key, which bypasses RLS. No public policies are added.
-- ---------------------------------------------------------------------------

alter table public.items enable row level security;
alter table public.purchases enable row level security;
alter table public.sales enable row level security;

-- Publishable-key mode: the server uses the anon role, so explicit policies are
-- required. This makes reads and writes public to anyone who can reach the app.
-- Remove these policies if you switch to SUPABASE_SERVICE_ROLE_KEY mode.
grant usage on schema public to anon;
grant select, insert on public.items to anon;
grant select, insert on public.purchases to anon;
grant select, insert on public.sales to anon;
drop policy if exists "anon_select_items" on public.items;
drop policy if exists "anon_insert_items" on public.items;
drop policy if exists "anon_select_purchases" on public.purchases;
drop policy if exists "anon_insert_purchases" on public.purchases;
drop policy if exists "anon_select_sales" on public.sales;
drop policy if exists "anon_insert_sales" on public.sales;

create policy "anon_select_items" on public.items for select to anon using (true);
create policy "anon_insert_items" on public.items for insert to anon with check (true);
create policy "anon_select_purchases" on public.purchases for select to anon using (true);
create policy "anon_insert_purchases" on public.purchases for insert to anon with check (true);
create policy "anon_select_sales" on public.sales for select to anon using (true);
create policy "anon_insert_sales" on public.sales for insert to anon with check (true);

-- ---------------------------------------------------------------------------
-- Numbering
-- ---------------------------------------------------------------------------

create sequence if not exists public.po_no_seq as integer start with 1;
create sequence if not exists public.invoice_no_seq as integer start with 1001;

create or replace function public.next_po_no()
returns text
language sql
volatile
as $$
  select 'PO-' || to_char(current_date, 'YYYY') || '-' || lpad(nextval('public.po_no_seq')::text, 2, '0');
$$;

create or replace function public.next_invoice_no()
returns text
language sql
volatile
as $$
  select 'INV-' || nextval('public.invoice_no_seq')::text;
$$;

-- ---------------------------------------------------------------------------
-- Atomic write functions
-- ---------------------------------------------------------------------------

create or replace function public.record_purchase(
  p_supplier text,
  p_item_id integer,
  p_qty integer,
  p_unit_cost numeric
)
returns public.purchases
language plpgsql
as $$
declare
  v_purchase public.purchases;
begin
  if p_qty is null or p_qty <= 0 then
    raise exception 'INVALID_QTY' using errcode = '23514';
  end if;

  if p_unit_cost is null or p_unit_cost < 0 then
    raise exception 'INVALID_UNIT_COST' using errcode = '23514';
  end if;

  if not exists (select 1 from public.items where id = p_item_id) then
    raise exception 'ITEM_NOT_FOUND' using errcode = '23503';
  end if;

  insert into public.purchases (po_no, purchase_date, supplier, item_id, qty, unit_cost)
  values (public.next_po_no(), current_date, p_supplier, p_item_id, p_qty, p_unit_cost)
  returning * into v_purchase;

  return v_purchase;
end;
$$;

create or replace function public.record_sale(
  p_customer text,
  p_item_id integer,
  p_qty integer,
  p_unit_price numeric
)
returns public.sales
language plpgsql
as $$
declare
  v_available integer;
  v_sale public.sales;
begin
  if p_qty is null or p_qty <= 0 then
    raise exception 'INVALID_QTY' using errcode = '23514';
  end if;

  if p_unit_price is null or p_unit_price < 0 then
    raise exception 'INVALID_UNIT_PRICE' using errcode = '23514';
  end if;

  -- Serialize concurrent sales for the same item.
  perform 1 from public.items where id = p_item_id for update;

  if not found then
    raise exception 'ITEM_NOT_FOUND' using errcode = '23503';
  end if;

  select coalesce(sum(qty), 0) into v_available
  from public.purchases
  where item_id = p_item_id;

  select v_available - coalesce(sum(qty), 0) into v_available
  from public.sales
  where item_id = p_item_id;

  if v_available < p_qty then
    raise exception 'INSUFFICIENT_STOCK' using errcode = '23514';
  end if;

  insert into public.sales (inv_no, sale_date, customer, item_id, qty, unit_price)
  values (public.next_invoice_no(), current_date, p_customer, p_item_id, p_qty, p_unit_price)
  returning * into v_sale;

  return v_sale;
end;
$$;

grant usage on sequence public.po_no_seq to anon;
grant usage on sequence public.invoice_no_seq to anon;
grant execute on function public.record_purchase(text, integer, integer, numeric) to anon;
grant execute on function public.record_sale(text, integer, integer, numeric) to anon;

